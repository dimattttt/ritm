const SPEECH_ERRORS = {
  "no-speech": "Не услышал речь. Попробуй ещё раз или напиши вопрос текстом.",
  "not-allowed": "Нет доступа к микрофону. Разреши доступ к микрофону в настройках браузера и попробуй снова.",
  "service-not-allowed": "Браузер запретил голосовой ввод. Разреши доступ к микрофону или напиши вопрос текстом.",
  "audio-capture": "Не удалось включить микрофон. Проверь, подключён ли он, или напиши вопрос текстом.",
  network: "Проблема с сетью при распознавании речи. Проверь интернет и попробуй снова.",
};

export function speechErrorMessage(code) {
  if (code === "aborted") return null;
  return SPEECH_ERRORS[code] || "Не получилось распознать речь. Попробуй ещё раз или напиши вопрос текстом.";
}
